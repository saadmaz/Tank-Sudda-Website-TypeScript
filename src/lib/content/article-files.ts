/**
 * Reads the raw article files from disk. Used only by the build-time generator
 * (scripts/generate-article-index.ts) and tests; the site itself imports the
 * generated module, because Cloudflare Workers have no file system.
 */
import fs from "node:fs";
import path from "node:path";

export interface ArticleSource {
  /** File name, e.g. "how-often-should-you-clean-your-water-tank.mdx". */
  id: string;
  raw: string;
}

export const ARTICLE_DIR = path.join(process.cwd(), "src", "content", "blog");
export const ARTICLE_INDEX_FILE = path.join(ARTICLE_DIR, "articles.generated.ts");

export function readArticleSources(dir: string = ARTICLE_DIR): ArticleSource[] {
  return fs
    .readdirSync(dir)
    .filter((file) => file.endsWith(".mdx"))
    .sort()
    .map((file) => ({ id: file, raw: fs.readFileSync(path.join(dir, file), "utf8") }));
}

/** Source of the generated module that bundles every article into the build. */
export function renderArticleIndex(sources: ArticleSource[]): string {
  return [
    "// Generated by `bun run content` from src/content/blog/*.mdx. Do not edit by hand.",
    'import type { ArticleSource } from "@/lib/content/article-files";',
    "",
    `export const articleSources: ArticleSource[] = ${JSON.stringify(sources, null, 2)};`,
    "",
  ].join("\n");
}
